// Generates the `/query` table catalog for the SQL console (autocompletion and the
// schema sidebar) from `docs/api/query-tables.md` — that document is itself generated from
// `cairn_query::catalog`, so the console's catalog follows exactly one source.
//
// Run: `npm run gen:tables`. `src/data/tables.gen.test.ts` regenerates and compares with the
// committed file (drift check).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const DOC_PATH = join(HERE, "..", "..", "docs", "api", "query-tables.md");
export const OUT_PATH = join(HERE, "..", "src", "data", "tables.gen.ts");

export type Column = { name: string; type: string; doc: string };
export type Table = { name: string; doc: string; columns: Column[] };

/** Strips light markdown (`code`, **bold**) — the sidebar shows plain text. */
const plain = (s: string) =>
  s
    .replace(/`([^`]*)`/g, "$1")
    .replace(/\*\*([^*]*)\*\*/g, "$1")
    .trim();

export function parse(md: string): Table[] {
  const out: Table[] = [];
  let cur: Table | null = null;
  for (const line of md.split("\n")) {
    const h = /^## `([a-z_][a-z0-9_]*)`\s*$/.exec(line);
    if (h?.[1]) {
      cur = { name: h[1], doc: "", columns: [] };
      out.push(cur);
      continue;
    }
    if (!cur) continue;
    const row = /^\| `([^`]+)` \| ([^|]+) \| (.*) \|\s*$/.exec(line);
    if (row?.[1] && row[2] && row[3] !== undefined) {
      cur.columns.push({ name: row[1], type: row[2].trim(), doc: plain(row[3]) });
    } else if (!cur.doc && line.trim() && !line.startsWith("|")) {
      cur.doc = plain(line);
    }
  }
  for (const t of out)
    if (t.columns.length === 0) throw new Error(`table ${t.name} has no columns`);
  return out;
}

export function generate(md: string): string {
  return `// Generated by \`npm run gen:tables\` from docs/api/query-tables.md — do not edit by hand.
export type Column = { name: string; type: string; doc: string };
export type Table = { name: string; doc: string; columns: Column[] };

export const TABLES: Table[] = ${JSON.stringify(parse(md), null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT_PATH, generate(readFileSync(DOC_PATH, "utf8")));
}
